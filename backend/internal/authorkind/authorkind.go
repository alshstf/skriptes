// Package authorkind — признак «служебного автора»: агрегата-псевдоавтора из
// INPX («Коллектив авторов», «Народные сказки», «Журнал «Юность»»,
// «Эротика и секс | Автор неизвестен | --»), который не человек.
//
// Правило общее для двух мест, поэтому живёт отдельно: классификатор в базе
// (metadata.ClassifyServiceAuthors — SQL, паттерны уходят параметром) и план
// межавторских серий импорта (importer.planMultiSeries — Go, служебный автор
// не делает серию своим «циклом»; на свежей базе меток ещё нет).
package authorkind

import "regexp"

// ServiceNamePatterns — регулярки по нормализованному имени (lower, «фамилия
// имя отчество» через один пробел). Синтаксис общий для Go (RE2) и PostgreSQL
// (ARE). Классы букв перечислены явно: в C-локали alpine-PG [[:alpha:]] не
// знает кириллицы (грабля с authorAlphaOrder).
//
// Консервативно (precision > recall, грабли №8/№13): полные фразы; префиксы
// издательских сущностей требуют продолжения после пробела («Газета Завтра»,
// но не фамилия «Газета»); «автор неизвестен»/«коллектив авторов» — отдельными
// словами где угодно в имени: librusec кладёт категорию в фамилию —
// «Эротика и секс | Автор неизвестен | --», «Автор неизвестен -- Античная
// литература» (прод 2026-09: 66 таких, людей среди них нет; #297).
var ServiceNamePatterns = []string{
	`^(без автора|народное творчество|народные сказки|устное народное творчество|русские народные сказки|сборник анекдотов)$`,
	`^(газета|журнал|альманах|редакция|издательство) `,
	`(^|[^а-яёa-z0-9])(автор неизвестен|автор неизвестный|неизвестный автор|коллектив авторов|авторов коллектив)([^а-яёa-z0-9]|$)`,
}

var serviceName = func() []*regexp.Regexp {
	res := make([]*regexp.Regexp, len(ServiceNamePatterns))
	for i, p := range ServiceNamePatterns {
		res[i] = regexp.MustCompile(p)
	}
	return res
}()

// IsServiceName — нормализованное имя похоже на служебного автора.
func IsServiceName(normalized string) bool {
	for _, re := range serviceName {
		if re.MatchString(normalized) {
			return true
		}
	}
	return false
}
