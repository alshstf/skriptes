package authorkind

import "testing"

func TestIsServiceName(t *testing.T) {
	for name, want := range map[string]bool{
		// Прод-кейсы.
		"коллектив авторов":                  true,
		"неизвестный автор":                  true,
		"народные сказки":                    true,
		"газета завтра":                      true,
		"журнал «вокруг света»":              true,
		"альманах «сделай сам»":              true,
		"эротика и секс автор неизвестен --": true,
		"эпосы， мифы， легенды и сказания автор неизвестен --": true,
		"история коллектив авторов --":                        true,
		"автор неизвестен -- античная литература":             true,
		"эпосы мифы легенды и сказания,автор неизвестен,--":   true,
		"cat_cat коллектив авторов":                           true,
		"литературная газета":                                 true,
		"авиация журнал":                                      true,
		"авиационный журнал «ас»":                             true,
		"интернет-журнал виноградова":                         true,
		"«левый поворот» №10 (2003 г) газета мрп":             true,
		"книгазета": false, // «газета» не отдельным словом
		// Люди и похожие слова.
		"гарднер лиза":             false,
		"газета":                   false, // фамилия без продолжения
		"газетов иван":             false,
		"коллективов пётр":         false,
		"неизвестный иван":         false,
		"авторов сергей":           false,
		"толстой лев николаевич":   false,
		"сборщиков автор иванович": false,
	} {
		if got := IsServiceName(name); got != want {
			t.Errorf("IsServiceName(%q) = %v, want %v", name, got, want)
		}
	}
}
