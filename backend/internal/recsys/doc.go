// десятилетию написания.
//
// Все сигналы пользователя — оценки, чтение (доля, дочитано, брошено,
// приобретено), просмотры карточек, полки, подчёркивания, скрытое из ленты и
// отказ оценивать — сводятся к РАБОТЕ (books.work_id): id работ и изданий —
// разные последовательности с пересечением (#399), сравнивать их нельзя.
// Загрузка сырых сигналов (signals.go) отделена от подсчёта (affinity.go):
// Score — чистая функция, веса — в одном месте (DefaultWeights) с комментарием
// «почему»; крутить по результатам харнесса (план recsys/01, задача 1.5).
// Affinity.Parts — трасса: из каких слагаемых сложилась близость.
//
// Явная обратная связь (фаза 3, план recsys/03): причины низкой оценки
// (RatingReason — «не моё» уходит минусом автору и жанру, «язык/перевод» —
// языку оригинала, «слишком длинно» читает «На вечер»), полка «Хочу прочитать»
// (намерение +2 и напоминание ToReadReminder), «не предлагать» автора/цикл
// (Profile.BlockedAuthors/BlockedSeries → Hydrate через Exclusions; каталог и
// поиск не трогает), настроение сессии (Mood — чип на Главной: веса жанров из
// mood-genres.json, ApplyMood пересортировывает секции правил, «Забытая
// классика» фильтрует сама) и «ваша средняя» по автору (AuthorRating).
//
